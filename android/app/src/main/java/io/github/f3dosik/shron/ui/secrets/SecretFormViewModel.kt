package io.github.f3dosik.shron.ui.secrets

import android.content.ContentResolver
import android.net.Uri
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import io.github.f3dosik.shron.R
import io.github.f3dosik.shron.ShronApplication
import io.github.f3dosik.shron.core.GeneratedPassword
import io.github.f3dosik.shron.core.GeneratorSettings
import io.github.f3dosik.shron.mobile.Mobile
import io.github.f3dosik.shron.mobile.SecretInput
import io.github.f3dosik.shron.ui.common.CoreViewModel
import io.github.f3dosik.shron.ui.common.PickedFile
import io.github.f3dosik.shron.ui.common.readPickedFile

/**
 * Форма нового секрета или изменения [existing]. Проверка полей (номер карты, срок и т.д.) —
 * в Go-ядре. Секрет на сервере определяется названием и типом, поэтому при изменении их не
 * меняют.
 */
class SecretFormViewModel(app: ShronApplication, val existing: SecretDetails? = null) : CoreViewModel(app) {

    val editing get() = existing != null

    var type by mutableStateOf(Mobile.TypeCredentials)
    var name by mutableStateOf("")
    var metadata by mutableStateOf("")

    var login by mutableStateOf("")
    var password by mutableStateOf("")
        private set
    var generated by mutableStateOf<GeneratedPassword?>(null)
        private set
    var generator by mutableStateOf(GeneratorSettings())
        private set

    /** Сайты и приложения: по одному на строку. */
    var uris by mutableStateOf("")

    var text by mutableStateOf("")

    var cardNumber by mutableStateOf("")
    var cardHolder by mutableStateOf("")
    var cardExpiry by mutableStateOf("")
    var cardCvv by mutableStateOf("")

    var file by mutableStateOf<PickedFile?>(null)
        private set

    init {
        if (existing != null) {
            type = existing.ref.type
            name = existing.ref.name
            metadata = existing.metadata
            login = existing.login
            password = existing.password
            uris = existing.uris
            text = existing.text
            cardNumber = existing.cardNumber
            cardHolder = existing.cardHolder
            cardExpiry = existing.cardExpiry
            cardCvv = existing.cardCvv
        }
    }

    fun updatePassword(value: String) {
        password = value
        generated = null
    }

    fun updateGenerator(settings: GeneratorSettings, regenerate: Boolean) {
        generator = settings
        if (regenerate) generatePassword()
    }

    fun generatePassword() = run {
        val result = core.generate(generator)
        password = result.password
        generated = result
    }

    fun pickFile(resolver: ContentResolver, uri: Uri) = run {
        val picked = readPickedFile(resolver, uri, MAX_FILE_SIZE) ?: throw validation(R.string.error_read_file)
        if (picked.data.size > MAX_FILE_SIZE) throw validation(R.string.file_too_large)
        file = picked
        if (name.isBlank() && !editing) name = picked.name
    }

    fun save(onSaved: (SecretRef) -> Unit) = run {
        // Заполняются только поля выбранного типа: данные с других вкладок не сохраняются.
        val input = SecretInput().apply {
            name = this@SecretFormViewModel.name
            type = this@SecretFormViewModel.type
            metadata = this@SecretFormViewModel.metadata
            when (this@SecretFormViewModel.type) {
                Mobile.TypeCredentials -> {
                    login = this@SecretFormViewModel.login
                    password = this@SecretFormViewModel.password
                    urIs = this@SecretFormViewModel.uris // setURIs() из gomobile
                }
                Mobile.TypeText -> text = this@SecretFormViewModel.text
                Mobile.TypeCard -> {
                    cardNumber = this@SecretFormViewModel.cardNumber.filterNot(Char::isWhitespace)
                    cardHolder = this@SecretFormViewModel.cardHolder
                    cardExpiry = this@SecretFormViewModel.cardExpiry
                    cardCVV = this@SecretFormViewModel.cardCvv
                }
                // Пустое содержимое при изменении оставляет прежний файл.
                Mobile.TypeBinary -> fileData = file?.data
            }
        }
        core.call { it.saveSecret(input, editing) }
        onSaved(SecretRef(input.name.trim(), input.type))
    }

    private companion object {
        /** Как maxFileSize в mobile/secrets.go; реальный предел задаёт сервер (SECRET_MAX_SIZE). */
        const val MAX_FILE_SIZE = 32 shl 20
    }
}
