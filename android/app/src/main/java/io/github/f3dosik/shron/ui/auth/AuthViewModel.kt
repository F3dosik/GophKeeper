package io.github.f3dosik.shron.ui.auth

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import io.github.f3dosik.shron.R
import io.github.f3dosik.shron.ShronApplication
import io.github.f3dosik.shron.core.GeneratedPassword
import io.github.f3dosik.shron.core.GeneratorSettings
import io.github.f3dosik.shron.core.ShronError
import io.github.f3dosik.shron.mobile.Mobile
import io.github.f3dosik.shron.ui.common.CoreViewModel

/**
 * Вход, регистрация, разблокировка и замена временного пароля. Один экземпляр на Activity:
 * временный пароль, введённый на экране входа или разблокировки, нужен экрану смены пароля.
 */
class AuthViewModel(app: ShronApplication) : CoreViewModel(app) {

    var registering by mutableStateOf(false)
        private set
    var login by mutableStateOf("")
    var password by mutableStateOf("")
        private set
    var confirm by mutableStateOf("")
        private set

    /** Сгенерированный мастер-пароль, пока пользователь его не изменил. */
    var generated by mutableStateOf<GeneratedPassword?>(null)
        private set

    /** Для мастер-пароля по умолчанию — парольная фраза: её проще запомнить и набирать. */
    var generator by mutableStateOf(GeneratorSettings(passphrase = true))
        private set

    var newPassword by mutableStateOf("")
    var newConfirm by mutableStateOf("")

    /** Временный пароль, который нужно заменить; не null — показывается экран смены пароля. */
    var temporaryPassword by mutableStateOf<String?>(null)
        private set

    /** Сервер прислал более слабые параметры Argon2id, чем запомнены на устройстве. */
    var kdfDowngrade by mutableStateOf<ShronError?>(null)
        private set
    private var kdfRetry: (suspend () -> Unit)? = null

    var info by mutableStateOf<String?>(null)
        private set

    fun updatePassword(value: String) {
        password = value
        generated = null
    }

    fun updateConfirm(value: String) {
        confirm = value
        generated = null
    }

    fun toggleRegistering() {
        registering = !registering
        password = ""
        confirm = ""
        generated = null
        info = null
        dismissError()
    }

    fun updateGenerator(settings: GeneratorSettings, regenerate: Boolean) {
        generator = settings
        if (regenerate) generateMasterPassword()
    }

    /** Генерирует мастер-пароль для новой учётки и подставляет его в оба поля. */
    fun generateMasterPassword() = run {
        val result = core.generate(generator)
        password = result.password
        confirm = result.password
        generated = result
    }

    fun submitSignIn() = run {
        info = null
        if (registering) {
            if (password != confirm) throw validation(R.string.passwords_mismatch)
            core.call { it.register(login, password) }
            registering = false
            confirm = ""
            generated = null
            info = string(R.string.account_created)
        }
        signIn()
    }

    fun unlock() = run { unlockVault() }

    fun completePasswordChange() = run {
        val temporary = temporaryPassword ?: return@run
        if (newPassword != newConfirm) throw validation(R.string.passwords_mismatch)
        core.call { it.completePasswordChange(temporary, newPassword) }
        cancelPasswordChange()
    }

    fun cancelPasswordChange() {
        temporaryPassword = null
        newPassword = ""
        newConfirm = ""
        dismissError()
    }

    /** Пользователь подтвердил, что сам сменил пароль с новыми параметрами: забыть старые и повторить. */
    fun acceptKdfChange() = run {
        val retry = kdfRetry ?: return@run
        val account = core.state.value.login.ifEmpty { login }
        kdfDowngrade = null
        kdfRetry = null
        core.call { it.acceptKDFChange(account) }
        retry()
    }

    fun rejectKdfChange() {
        kdfDowngrade = null
        kdfRetry = null
        password = ""
    }

    fun logout() = run {
        core.call { it.logout(false) }
        password = ""
        confirm = ""
        cancelPasswordChange()
    }

    override fun onError(e: ShronError) {
        if (e.code == Mobile.CodeKDFDowngrade) kdfDowngrade = e else super.onError(e)
    }

    private suspend fun signIn() {
        kdfRetry = ::signIn
        val changeRequired = core.call { it.signIn(login, password) }
        afterAuth(changeRequired)
    }

    private suspend fun unlockVault() {
        kdfRetry = ::unlockVault
        core.call { it.unlock(password) }
        // Unlock не сообщает о временном пароле: хранилище тогда просто остаётся заблокированным.
        afterAuth(changeRequired = !core.state.value.unlocked)
    }

    private fun afterAuth(changeRequired: Boolean) {
        kdfRetry = null
        if (changeRequired) temporaryPassword = password
        password = ""
        confirm = ""
    }
}
